export function translate(locale: Locale, key: TextKey): string { return (locale === 'zh-Hant' ? zh : en)[key]; }
export function localeFromLanguage(language: string): Locale { return language.toLowerCase().startsWith('zh') ? 'zh-Hant' : 'en'; }
export function formatBytes(bytes: number, locale: Locale): string {
  if (!Number.isFinite(bytes) || bytes < 0) return '—';
  const units = ['B', 'KiB', 'MiB', 'GiB', 'TiB']; let index = 0, value = bytes;
  while (value >= 1024 && index < units.length - 1) { value /= 1024; index++; }
  return `${new Intl.NumberFormat(locale, { maximumFractionDigits: index ? 2 : 0 }).format(value)} ${units[index]}`;
}

/** Translate known product outcomes; retain unknown technical codes as a separate detail. */
export function diagnosticText(locale: Locale, code: string): string {
  const keys: Readonly<Record<string, TextKey>> = {
    'program-not-required': 'diagIgnoredProgram', 'unsupported-file-type': 'diagUnsupported',
    'excluded-profile': 'diagExcluded', 'unassigned-content-scope': 'diagUnassigned',
    'duplicate-file-path': 'diagDuplicate', 'unsafe-file-path': 'diagUnsafe',
    'checksum-absent': 'diagChecksumAbsent', 'checksum-unverified': 'diagChecksumUnverified',
    'archive-unverified': 'diagChecksumBlocked', 'checksum-mismatch': 'diagChecksumMismatch',
    'database-rejected': 'diagDatabase', 'ambiguous-archive-layout': 'diagMalformed',
  };
  const key = (Object.hasOwn(keys, code) ? keys[code] : undefined) ?? (code.includes('limit') || code === 'browser-read-budget' ? 'diagLimit' :
    /^(archive-|mix-|source-read|entry-|index-|header-|payload-|encrypted-|ambiguous-layout|truncated)/.test(code) ? 'diagMalformed' : 'diagUnknown');
  return translate(locale, key);
}
